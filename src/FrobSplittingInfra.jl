function in1FInjectiveIdeal(g,p)
    # don't need this because exponent_vectors will have 
    # no elements for the zero polynomial
    g == zero(g) && return true

#     p = characteristic(parent(g))

    f = g#^(2p-2)

    for i in 1:length(f)
        ev = exponent_vector(f,i)
        c = coeff(f,i)

        ev_lt_p = ev .< p
        # println(ev)
        # println(c)
        #println(all(ev .< 2p))
