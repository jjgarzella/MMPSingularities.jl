function bracketpower(I,m)
    R = base_ring(I)

    res = zeros(R,0)
    for g in gens(I)
        new_gen = g^m
        push!(res,new_gen)
    end

    ideal(R,res)
end


function fedderColonIdeal(I)
    p = characteristic(base_ring(I))
    bracketpower(I,p):I
end


