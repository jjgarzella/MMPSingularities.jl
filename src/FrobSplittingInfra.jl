    p = poly.parent.data.n
    R = parent(poly)

    originallift = map_coefficients(x -> lift(ZZ, x),poly)

    nocrossterms = sum(terms(originallift) .^ p)
    withcrossterms = originallift ^ p
    crossterms = withcrossterms - nocrossterms
