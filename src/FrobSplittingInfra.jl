        #println(c % p != 0)

        if all(ev_lt_p) && (c % p^2 != 0)
            # println("found type 1")
          
            # We not in the power of the maximal ideal, we don't have any
            # powers that are big enough
            return false
        elseif all(ev .< 2p) && 
               count(==(false), ev_lt_p) == 1 &&
               c % p != 0
            # println("found type 2")

            return false
        end
    end

    true
end

function is1FInjective(f,p)
